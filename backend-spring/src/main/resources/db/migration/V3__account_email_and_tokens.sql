-- Version 3 (Brief! 2.4): an email address on accounts, and one-time links.
--
-- Written, like V1 and V2, in the SQL that H2 and PostgreSQL share. Flyway runs this file once
-- on every database that is at version 2, and never again. V1 and V2 are not touched: a
-- migration that has run is never edited.

-- 1. The email address of an account.
--    It may be empty: accounts from before 2.4 have none until their owner adds one, and the
--    compat mode of the training contract never asks for one. Where it is present it is stored
--    in lower case and must be unique. A unique constraint allows any number of empty values.
alter table account add column email varchar(254);
alter table account add constraint uq_account_email unique (email);

-- 2. When the address was confirmed through the emailed link, in seconds since 1970.
--    Empty means "not confirmed yet". A time says more than a yes/no column would, and it is
--    the same kind of column message.time_posted_epoch already is.
alter table account add column email_verified_at bigint;

-- 3. The number of the account's current "generation" of login tokens. Every token carries the
--    number that was current when it was issued, and is accepted only while the two are equal.
--    Setting a new password adds one, which signs the account out everywhere at once.
--    Existing rows get 0 through the default, and tokens from before this release count as 0 too.
alter table account add column token_version integer default 0 not null;

-- 4. One-time links: "confirm this address" and "set a new password".
--    The link carries a random secret. Only its SHA-256 hash is stored here, as with passwords:
--    someone who can read this table still cannot use the links.
create table account_token (
    token_id   integer generated by default as identity,
    account_id integer not null,
    purpose    varchar(16) not null,          -- verify or reset
    token_hash varchar(64) not null,          -- 64 hexadecimal characters
    expires_at bigint not null,               -- seconds since 1970
    used_at    bigint,                        -- empty until the link has been used
    created_at bigint not null,
    constraint pk_account_token primary key (token_id),
    constraint uq_account_token_hash unique (token_hash),
    -- The links of an account go with the account.
    constraint fk_account_token_account
        foreign key (account_id) references account (account_id) on delete cascade
);

-- "The links of this account for this purpose", used when a new link replaces the old ones.
create index idx_account_token_account on account_token (account_id, purpose);
