-- Brief! 2.7: addresses that cannot receive mail.
--
-- Resend, the service that delivers Brief!s mail, tells the application through a signed
-- webhook when a receiving server refused a mail for good (a hard bounce), or when the address
-- is on Resends suppression list. One row per address. For 30 days Brief! says so to the member
-- (or to the board owner, for an invitation); for the first day it sends that address nothing.
-- After that one more try clears the row (see service/EmailBounces.java).
--
-- The address is not tied to an account: a mistyped address in an invitation belongs to nobody.
-- Rows older than 30 days are deleted, and a row goes at once when its account is deleted or the
-- address is confirmed after all.
--
-- Written in the SQL that H2 and PostgreSQL share, like V1 to V4. No apostrophes in comments.

create table email_bounce (
    bounce_id   integer generated by default as identity,
    address     varchar(254) not null,             -- lower case, as on account.email
    kind        varchar(16) not null,              -- bounced or suppressed
    reason      varchar(300),                      -- the receiving servers words, shortened
    bounced_at  bigint not null,                   -- seconds since 1970
    constraint pk_email_bounce primary key (bounce_id),
    constraint uq_email_bounce_address unique (address)
);

create index idx_email_bounce_at on email_bounce (bounced_at);
