-- Brief! 2.5: invitations.
--
-- On a closed board a new member joins through a link that a member of the board (its owner,
-- in 2.5) sent. Each invitation is one row. Like the links of V3, the row holds only the
-- SHA-256 hash of the secret in the link, never the secret itself.
--
-- An invitation either names an email address (it was mailed there, so whoever opens it can
-- read that inbox, and the new account starts with that address confirmed) or names none (the
-- inviter copied the link to pass it on by other means, and the new member confirms an address
-- as usual).
--
-- Written in the SQL that H2 and PostgreSQL share, like V1 to V3. No apostrophes in comments.

create table invitation (
    invitation_id integer generated by default as identity,
    inviter_id    integer not null,
    email         varchar(254),                  -- lower case, or empty for a link to pass on
    token_hash    varchar(64) not null,          -- 64 hexadecimal characters
    created_at    bigint not null,               -- seconds since 1970
    expires_at    bigint not null,
    used_at       bigint,                        -- empty until an account was created with it
    used_by       integer,                       -- that account, while it exists
    constraint pk_invitation primary key (invitation_id),
    constraint uq_invitation_token_hash unique (token_hash),
    -- The invitations of a member go with the member.
    constraint fk_invitation_inviter
        foreign key (inviter_id) references account (account_id) on delete cascade,
    -- An account that joined through an invitation may be deleted later. The invitation stays,
    -- as a record that it was used, and forgets by whom.
    constraint fk_invitation_used_by
        foreign key (used_by) references account (account_id) on delete set null
);

create index idx_invitation_inviter on invitation (inviter_id, invitation_id);
create index idx_invitation_email on invitation (email);
