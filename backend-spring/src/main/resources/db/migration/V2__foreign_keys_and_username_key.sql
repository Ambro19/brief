-- V2 (Brief! 2.3.0): foreign keys, an index for "posts by one member", and usernames that are
-- unique whatever the capitals.
--
-- This file also runs against databases that were created by 2.2 or earlier, so each step
-- first makes sure the existing rows can satisfy the new rule.

-- ---------------------------------------------------------------------------------------
-- 1. A database from 2.0 or 2.1 has no mention table. Create it if it is missing.
--    (MentionBackfill then fills it from the existing posts at start-up.)
-- ---------------------------------------------------------------------------------------
create table if not exists mention (
    mention_id integer generated by default as identity,
    message_id integer not null,
    account_id integer not null,
    constraint pk_mention primary key (mention_id),
    constraint uq_mention_message_account unique (message_id, account_id)
);

create index if not exists idx_mention_account_message on mention (account_id, message_id);

-- ---------------------------------------------------------------------------------------
-- 2. Rows that point at nothing cannot be given a foreign key. The application never writes
--    such rows, so on a normal database these three statements delete nothing.
-- ---------------------------------------------------------------------------------------
delete from message where posted_by not in (select account_id from account);
delete from mention where message_id not in (select message_id from message);
delete from mention where account_id not in (select account_id from account);

-- ---------------------------------------------------------------------------------------
-- 3. Foreign keys: from now on the database itself refuses a post without an author and a
--    mention without its post or its member.
--
--    "on delete cascade" on the two mention keys: when a post (or, later, an account) is
--    deleted, its mention rows go with it. There is no cascade from account to message:
--    what happens to a member's posts when the account is deleted is a decision for the
--    milestone that adds account deletion, so for now the database refuses that delete.
--
--    The index serves "posts by one member, newest first" (GET /accounts/{id}/messages) and
--    the foreign-key check on account. PostgreSQL does not index a foreign key by itself.
-- ---------------------------------------------------------------------------------------
create index idx_message_author on message (posted_by, message_id);

alter table message add constraint fk_message_author
    foreign key (posted_by) references account (account_id);

alter table mention add constraint fk_mention_message
    foreign key (message_id) references message (message_id) on delete cascade;

alter table mention add constraint fk_mention_account
    foreign key (account_id) references account (account_id) on delete cascade;

-- ---------------------------------------------------------------------------------------
-- 4. username_key: the username in lower case, unique. "Maya" and "maya" are now one name.
--    The application writes this column itself for every new account (Account.keyOf); the
--    statements below fill it for accounts that already exist.
--
--    If two existing accounts differ only in capitals, the older one keeps the name. The
--    newer one (say "Maya", account 7, beside an older "maya") gets the key "maya#7". The
--    new-username rule does not allow "#", so nobody can register that name. Its posts stay,
--    and its owner can still sign in by typing maya#7 with the account's own password.
--
--    Two limits, both only for names made by sending requests straight to the API of 2.2 or
--    earlier (the web app never allowed them): a name with a tab or line break around it gets
--    a key that sign-in does not compute, so that account cannot sign in until its row is
--    corrected by hand; and this file stops with an error if a name is so long that the "#"
--    and the id no longer fit in 255 characters.
--
--    Before the first start of 2.3 on a database you care about, copy it (for H2: the h2
--    folder). PostgreSQL undoes a migration that fails half-way. H2 cannot.
-- ---------------------------------------------------------------------------------------
alter table account add column username_key varchar(255);

update account set username_key = lower(trim(username));

update account
   set username_key = username_key || '#' || cast(account_id as varchar(20))
 where exists (select 1
                 from account older
                where older.username_key = account.username_key
                  and older.account_id < account.account_id);

alter table account alter column username_key set not null;

alter table account add constraint uq_account_username_key unique (username_key);
