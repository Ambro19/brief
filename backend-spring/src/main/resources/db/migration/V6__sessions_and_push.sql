-- Brief! 2.8: sessions kept in the database, and push subscriptions.
--
-- account_session: one row per sign-in. The login token carries the row id ("sid"), and a token
-- is accepted only while its row exists and has not expired. That is what makes signing out
-- permanent (until 2.7 the list of signed-out tokens lived in memory, and a restart forgot it),
-- and what makes "Sign out everywhere else" possible.
--   stay = false: the session ends 12 hours after signing in, as before 2.8.
--   stay = true:  "Stay signed in on this device". The session ends after 30 days without use;
--                 each use moves that day forward (at most once an hour, to spare the database).
-- device is a short label made from the browser's User-Agent, such as "Chrome on Windows". The
-- full User-Agent and the IP address are not stored.
--
-- push_subscription: where to deliver a notification for one browser on one device (Web Push,
-- RFC 8030). The endpoint is an address at the browser maker's push service (Google, Mozilla,
-- Apple, Microsoft); p256dh and auth are the browser's public key and secret, with which the
-- notification is encrypted so that the push service cannot read it (RFC 8291). Each
-- subscription belongs to the session that turned it on: signing out of that session deletes
-- it (on delete cascade), so a device that was signed out receives nothing more.
--
-- Written in the SQL that H2 and PostgreSQL share, like V1 to V5. No apostrophes in comments.

create table account_session (
    session_id    integer generated by default as identity,
    account_id    integer not null,
    stay          boolean not null,
    device        varchar(60) not null,
    created_at    bigint not null,                 -- seconds since 1970
    last_used_at  bigint not null,
    expires_at    bigint not null,
    constraint pk_account_session primary key (session_id),
    constraint fk_account_session_account foreign key (account_id) references account (account_id) on delete cascade
);

create index idx_account_session_account on account_session (account_id);
create index idx_account_session_expires on account_session (expires_at);

create table push_subscription (
    subscription_id  integer generated by default as identity,
    account_id       integer not null,
    session_id       integer not null,
    endpoint         varchar(1000) not null,
    p256dh           varchar(100) not null,         -- the browser public key, base64url
    auth             varchar(40) not null,          -- the browser secret, base64url
    created_at       bigint not null,
    constraint pk_push_subscription primary key (subscription_id),
    constraint uq_push_subscription_endpoint unique (endpoint),
    constraint fk_push_subscription_account foreign key (account_id) references account (account_id) on delete cascade,
    constraint fk_push_subscription_session foreign key (session_id) references account_session (session_id) on delete cascade
);

create index idx_push_subscription_account on push_subscription (account_id);
create index idx_push_subscription_session on push_subscription (session_id);
