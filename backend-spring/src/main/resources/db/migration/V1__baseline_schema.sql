-- V1: the three tables as Brief! 2.2.0 had them: the same tables, columns, types and rules.
--
-- One difference to keep in mind: here the primary keys and the unique rule on username have
-- names (pk_account, uq_account_username, ...). A database that Hibernate created for 2.2 has
-- the same rules under names Hibernate made up. So a later migration must never drop or change
-- one of these by its name; it would work on a new database and fail on an old one.
--
-- Flyway runs each file in this folder once per database, in the order of the number after
-- "V", and records it in the table flyway_schema_history. A file that has been run is never
-- edited again: a change to the schema is always a NEW file with the next number.
--
-- On an empty database this file runs first. On a database that 2.2 or an earlier version
-- already created, Flyway skips it ("baseline", see application.properties) and starts at V2.
--
-- The SQL is the subset that H2 and PostgreSQL both accept, so the same files serve your own
-- machine, the tests and production.
--   "generated by default as identity" = the database numbers the rows itself (1, 2, 3, ...).

create table account (
    account_id integer generated by default as identity,
    username   varchar(255) not null,
    password   varchar(255) not null,
    constraint pk_account primary key (account_id),
    constraint uq_account_username unique (username)
);

create table message (
    message_id        integer generated by default as identity,
    posted_by         integer not null,
    message_text      varchar(255) not null,
    time_posted_epoch bigint not null,
    constraint pk_message primary key (message_id)
);

create table mention (
    mention_id integer generated by default as identity,
    message_id integer not null,
    account_id integer not null,
    constraint pk_mention primary key (mention_id),
    constraint uq_mention_message_account unique (message_id, account_id)
);

create index idx_mention_account_message on mention (account_id, message_id);
